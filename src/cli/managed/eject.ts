import path from 'node:path';

import { type AppConfig, toJsLiteral } from '../commands/scaffold/generate-app.js';
import { dotRelative } from '../util/files.js';

// eject converts the publishContent section of the project file into
// compute-js/publish-content.config.js. A JavaScript file cannot be split
// without a parser, so eject works on the loaded value: it can write data
// (strings, numbers, booleans, null, arrays, and plain objects), but not
// functions or regular expressions.

// The paths in the value that are not data, for example 'assetInclusionTest'.
export function findNonDataPaths(value: unknown, at: string = ''): string[] {
  if (value === null || value === undefined || [ 'string', 'number', 'boolean' ].includes(typeof value)) {
    return [];
  }
  if (Array.isArray(value)) {
    return value.flatMap((x, i) => findNonDataPaths(x, `${at}[${i}]`));
  }
  if (typeof value === 'object' && Object.getPrototypeOf(value) === Object.prototype) {
    return Object.entries(value as Record<string, unknown>).flatMap(([ k, v ]) => findNonDataPaths(v, at === '' ? k : `${at}.${k}`));
  }
  return [ at === '' ? '(publishContent)' : at ];
}

// The publishContent that scaffold --managed writes for an app config, with
// paths relative to baseDir. If the section of a project is equal to it, eject
// writes the same publish-content.config.js as an ejected scaffold.
export function scaffoldedPublishContent(config: AppConfig, baseDir: string): Record<string, unknown> {
  const publicDirPrefix = config.publicDir !== config.rootDir ? config.publicDir.slice(config.rootDir.length).split(path.sep).join('/') : '';
  const assetKey = (file: string | undefined) => file != null ? file.slice(config.rootDir.length).split(path.sep).join('/') : false;
  return {
    rootDir: dotRelative(baseDir, config.rootDir).split(path.sep).join('/'),
    server: {
      ...(publicDirPrefix !== '' ? { publicDirPrefix } : {}),
      staticItems: config.staticDirs.map(dir => {
        const item = dir.slice(config.publicDir.length).split(path.sep).join('/');
        return item.endsWith('/') ? item : item + '/';
      }),
      allowedEncodings: [ 'br', 'gzip' ],
      spaFile: assetKey(config.spaFilename),
      notFoundPageFile: assetKey(config.notFoundPageFilename),
      autoExt: config.autoExt,
      autoIndex: config.autoIndex,
    },
  };
}

function canonical(value: unknown): string {
  return JSON.stringify(value, (_key, v) => {
    if (v != null && typeof v === 'object' && !Array.isArray(v)) {
      return Object.fromEntries(Object.keys(v).sort().filter(k => v[k] !== undefined).map(k => [ k, v[k] ]));
    }
    return v;
  });
}

export function isScaffoldedPublishContent(raw: unknown, config: AppConfig, projectDir: string): boolean {
  return canonical(raw) === canonical(scaffoldedPublishContent(config, projectDir));
}

// publish-content.config.js for a publishContent section that is data. Paths
// are written again relative to the new directory, so that they point at the
// same directories.
export function renderPublishContentConfig(raw: Record<string, unknown>, projectDir: string, appDir: string): string {
  const value: Record<string, unknown> = { ...raw };
  if (typeof value.rootDir === 'string') {
    value.rootDir = dotRelative(appDir, path.resolve(projectDir, value.rootDir)).split(path.sep).join('/');
  }
  return `\
/*
 * Generated by @fastly/compute-js-static-publish (eject), from the
 * publishContent section of static-publish.project.js.
 */

/** @type {import('@fastly/compute-js-static-publish').PublishContentConfig} */
const config = ${toJsLiteral(value)};

export default config;
`;
}
